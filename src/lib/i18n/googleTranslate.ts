let scriptLoaded = false;
let scriptLoading = false;
const listeners: Array<() => void> = [];

export function isGoogleTranslateActive(): boolean {
  if (typeof document === 'undefined' || typeof document.cookie !== 'string') return false;
  const match = document.cookie.match(/(?:^|; )googtrans=([^;]*)/);
  if (!match) return false;
  const val = decodeURIComponent(match[1]);
  return Boolean(val && val !== '/auto/en' && val !== '/en/en');
}

export function getCurrentGoogleTranslateLanguage(): string | null {
  if (typeof document === 'undefined' || typeof document.cookie !== 'string') return null;
  const match = document.cookie.match(/(?:^|; )googtrans=([^;]*)/);
  if (!match) return null;
  const val = decodeURIComponent(match[1]);
  const parts = val.split('/');
  return parts[parts.length - 1] || null;
}

export function loadGoogleTranslateScript(): Promise<void> {
  return new Promise((resolve) => {
    if (typeof window === 'undefined') {
      resolve();
      return;
    }

    if (window.google?.translate) {
      resolve();
      return;
    }

    if (scriptLoaded) {
      resolve();
      return;
    }

    listeners.push(resolve);

    if (scriptLoading) {
      return;
    }

    scriptLoading = true;

    // Define the global callback
    window.googleTranslateElementInit = () => {
      try {
        if (window.google?.translate?.TranslateElement) {
          new window.google.translate.TranslateElement(
            {
              pageLanguage: 'en',
              autoDisplay: false,
            },
            'google_translate_element'
          );
        }
      } catch (err) {
        console.warn('Google Translate initialization note:', err);
      }
      scriptLoaded = true;
      scriptLoading = false;
      while (listeners.length > 0) {
        const cb = listeners.shift();
        if (cb) cb();
      }
    };

    const script = document.createElement('script');
    script.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
    script.async = true;
    script.onerror = () => {
      console.warn('Google Translate script could not load (e.g. offline or blocked).');
      scriptLoading = false;
    };
    document.body.appendChild(script);
  });
}

/**
 * Trigger translation to a given target language code via Google Translate cookie & combo.
 */
export function translatePageTo(targetLang: string): void {
  if (typeof document === 'undefined') return;

  // Set the standard googtrans cookie across root and domain
  const cookieVal = `/auto/${targetLang}`;
  const hostname = window.location.hostname;
  document.cookie = `googtrans=${cookieVal}; path=/; max-age=31536000`;
  if (hostname && !hostname.includes('localhost') && hostname.includes('.')) {
    document.cookie = `googtrans=${cookieVal}; domain=.${hostname}; path=/; max-age=31536000`;
  }

  // Find the combo box created by Google Translate and change its value
  const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
  if (select) {
    select.value = targetLang;
    select.dispatchEvent(new Event('change', { bubbles: true }));
  } else {
    // If element is not yet created, ensure script loads then reload/apply
    loadGoogleTranslateScript().then(() => {
      setTimeout(() => {
        const retrySelect = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
        if (retrySelect) {
          retrySelect.value = targetLang;
          retrySelect.dispatchEvent(new Event('change', { bubbles: true }));
        } else {
          window.location.reload();
        }
      }, 300);
    });
  }
}

/**
 * Reset Google Translate back to native app text
 */
export function resetGoogleTranslate(): void {
  if (typeof document === 'undefined') return;
  const hostname = window.location.hostname;
  document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
  if (hostname && !hostname.includes('localhost') && hostname.includes('.')) {
    document.cookie = `googtrans=; domain=.${hostname}; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;`;
  }

  // If Google toolbar iframe exists, try to click close or revert
  const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
  if (select) {
    select.value = 'en';
    select.dispatchEvent(new Event('change', { bubbles: true }));
  }

  window.location.reload();
}
