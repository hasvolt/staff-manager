// Store original text of DOM elements to enable instant restoration to English
const originalTextNodes = new WeakMap<Node, string>();
const originalInputPlaceholders = new WeakMap<HTMLInputElement | HTMLTextAreaElement, string>();

let activeLangCode: string = 'en';
let translationObserver: MutationObserver | null = null;
let isTranslatingDOM = false;

/**
 * Translate a single text string according to the active language
 */
export function translateText(text: string, langCode: string = activeLangCode): string {
  if (!text || langCode === 'en') return text;
  const dict = PHRASE_DICTIONARY[langCode];
  if (!dict) return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // Direct match
  if (dict[trimmed]) {
    return text.replace(trimmed, dict[trimmed]);
  }

  // Check case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(dict)) {
    if (key.toLowerCase() === lower) {
      return text.replace(trimmed, val);
    }
  }

  return text;
}

/**
 * Recursively walk DOM nodes and translate text
 */
function translateNode(node: Node, langCode: string) {
  if (!node) return;

  // Skip scripts, styles, translate containers, inputs
  if (node.nodeType === Node.ELEMENT_NODE) {
    const el = node as HTMLElement;
    const tagName = el.tagName.toUpperCase();
    if (
      tagName === 'SCRIPT' ||
      tagName === 'STYLE' ||
      tagName === 'NOSCRIPT' ||
      tagName === 'CODE' ||
      el.id === 'google_translate_element' ||
      el.classList?.contains('skiptranslate') ||
      el.classList?.contains('no-translate')
    ) {
      return;
    }

    // Translate placeholder
    if (tagName === 'INPUT' || tagName === 'TEXTAREA') {
      const input = el as HTMLInputElement | HTMLTextAreaElement;
      if (input.placeholder) {
        if (!originalInputPlaceholders.has(input)) {
          originalInputPlaceholders.set(input, input.placeholder);
        }
        const orig = originalInputPlaceholders.get(input) || input.placeholder;
        if (langCode === 'en') {
          input.placeholder = orig;
        } else {
          input.placeholder = translateText(orig, langCode);
        }
      }
      return;
    }
  }

  if (node.nodeType === Node.TEXT_NODE) {
    const textNode = node as Text;
    const text = textNode.nodeValue;
    if (!text || !text.trim()) return;

    if (!originalTextNodes.has(textNode)) {
      originalTextNodes.set(textNode, text);
    }

    const origText = originalTextNodes.get(textNode) || text;
    if (langCode === 'en') {
      if (textNode.nodeValue !== origText) {
        textNode.nodeValue = origText;
      }
    } else {
      const translated = translateText(origText, langCode);
      if (translated !== textNode.nodeValue) {
        textNode.nodeValue = translated;
      }
    }
    return;
  }

  // Recurse children
  let child = node.firstChild;
  while (child) {
    translateNode(child, langCode);
    child = child.nextSibling;
  }
}

/**
 * Apply full application translation across the entire DOM
 */
export function applyFullAppTranslation(langCode: string): void {
  activeLangCode = langCode;
  if (typeof document === 'undefined') return;

  isTranslatingDOM = true;
  try {
    translateNode(document.body, langCode);
  } finally {
    isTranslatingDOM = false;
  }

  // Ensure continuous translation of newly mounted React components
  if (!translationObserver && typeof MutationObserver !== 'undefined') {
    translationObserver = new MutationObserver((mutations) => {
      if (isTranslatingDOM || activeLangCode === 'en') return;
      isTranslatingDOM = true;
      try {
        for (const mutation of mutations) {
          if (mutation.type === 'childList') {
            mutation.addedNodes.forEach((n) => translateNode(n, activeLangCode));
          }
        }
      } finally {
        isTranslatingDOM = false;
      }
    });

    translationObserver.observe(document.body, {
      childList: true,
      subtree: true,
    });
  }
}

/**
 * Return to English: Immediately revert all translated nodes back to original English strings
 */
export function returnToEnglish(): void {
  activeLangCode = 'en';
  if (typeof document === 'undefined') return;

  isTranslatingDOM = true;
  try {
    translateNode(document.body, 'en');
  } finally {
    isTranslatingDOM = false;
  }

  if (translationObserver) {
    translationObserver.disconnect();
    translationObserver = null;
  }
}
